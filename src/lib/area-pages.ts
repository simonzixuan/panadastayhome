export function getAreaLinksForCity(citySlug: string) {
  return Object.entries(areaPages)
    .filter(([, page]) => page.citySlug === citySlug)
    .map(([slug, page]) => ({ label: `${page.area} 租房`, href: `/area/${slug}` }))
}

export function getRelatedAreaLinks(currentSlug: string) {
  const current = areaPages[currentSlug as keyof typeof areaPages]
  if (!current) return []

  return Object.entries(areaPages)
    .filter(([slug, page]) => slug !== currentSlug && page.citySlug === current.citySlug)
    .map(([slug, page]) => ({ label: `${page.area} 租房`, href: `/area/${slug}` }))
}

export function getAreaLinkForListing(listing: {
  title?: string | null
  address?: string | null
  city?: string | null
  district?: string | null
  state?: string | null
  country?: string | null
}) {
  const normalizedCountry = listing.country === "United States"
    ? "US"
    : listing.country === "Canada"
      ? "CA"
      : listing.country?.toUpperCase()
  const searchable = [listing.title, listing.address, listing.city, listing.district]
    .filter(Boolean)
    .join(" ")
    .toLowerCase()

  const match = Object.entries(areaPages).find(([, page]) =>
    listing.state?.toUpperCase() === page.state &&
    normalizedCountry === page.country &&
    searchable.includes(page.area.toLowerCase())
  )

  if (!match) return null
  const [slug, page] = match
  return { label: `${page.area} 租房`, href: `/area/${slug}` }
}
